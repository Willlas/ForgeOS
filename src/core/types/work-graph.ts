// ============================================================================
// Graph Operations
// ============================================================================

/**
 * Result of adding a node to the graph.
 */
export interface NodeAddedResult {
  success: true;
  node: WorkNode;
  unblockedNodes: string[];
}

export interface NodeAddConflictError {
  success: false;
  error: "node_exists" | "invalid_dependency" | "circular_dependency";
  details: string;
}

export type AddNodeResult = NodeAddedResult | NodeAddConflictError;

/**
 * Result of removing a node from the graph.
 */
export interface NodeRemovedResult {
  success: true;
  nodeId: string;
  affectedNodes: string[];
}

// ============================================================================
// Priority Scoring
// ============================================================================

/**
 * Components used in priority scoring for work nodes.
 */
export interface PriorityScore {
  /** Base priority (1-10) */
  basePriority: number;

  /** Dependency boost (nodes with more dependents get boosted) */
  dependencyBoost: number;

  /** Blocking decay (waiting/blocked nodes get penalized) */
  blockingDecay: number;

  /** Recency bonus (newer ready nodes get slight bonus) */
  recencyBonus: number;

  /** Final composite score */
  totalScore: number;
}

/**
 * Configuration for the priority scoring algorithm.
 */
export interface PriorityScoringConfig {
  /** Weight for base priority (default: 1.0) */
  basePriorityWeight: number;

  /** Maximum dependency boost (default: 2.0) */
  maxDependencyBoost: number;

  /** Blocking penalty factor (default: 0.5) */
  blockingPenalty: number;

  /** Recency half-life in milliseconds (default: 1 hour) */
  recencyHalfLifeMs: number;
}

// ============================================================================
// Default scoring configuration
// ============================================================================

export const DEFAULT_SCORING_CONFIG: PriorityScoringConfig = {
  basePriorityWeight: 1.0,
  maxDependencyBoost: 2.0,
  blockingPenalty: 0.5,
  recencyHalfLifeMs: 3_600_000, // 1 hour
};

// ============================================================================
// Node ID Generation
// ============================================================================

/**
 * Format for generated node IDs.
 * Pattern: prefix-sequential-number
 */
export interface NodeIdConfig {
  /** Prefix (e.g., "research", "impl", "test") */
  prefix: string;
  /** Starting counter (default: 1) */
  startCounter?: number;
}

let nodeCounter = 0;

/**
 * Generates sequential node IDs.
 * Thread-safe within a single process context.
 */
export function generateNodeId(config?: Partial<NodeIdConfig>): string {
  const prefix = config?.prefix ?? "task";
  nodeCounter++;
  return `${prefix}-${nodeCounter}`;
}

