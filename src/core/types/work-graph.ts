/**
 * Work Graph Types - Domain model for executable engineering work items.
 *
 * The Work Graph represents the executable engineering state of the repository.
 * Unlike a task list, it models dependencies, parallelism, risk, knowledge generation.
 *
 * @module core/types/work-graph
 */

// ============================================================================
// Node Types
// ============================================================================

/**
 * Atomic engineering work categories.
 * Each node type represents one unit of engineering effort.
 */
export enum WorkNodeType {
  // Core engineering
  Research = "research",
  Prototype = "prototype",
  Implementation = "implementation",
  Testing = "testing",

  // Documentation
  Documentation = "documentation",
  ArchitectureDecision = "adr",

  // Analysis
  Benchmark = "benchmark",
  Review = "review",
  Profiling = "profiling",

  // Quality
  Refactoring = "refactoring",
  Validation = "validation",

  // Planning
  Planning = "planning",
  Design = "design",

  // Infrastructure
  Deployment = "deployment",
  Experiment = "experiment",

  // Reverse engineering
  ReverseEngineering = "reverse_engineering",

  // Knowledge production
  KnowledgeCapture = "knowledge_capture",
}

/**
 * Work node states following the full lifecycle.
 * Nodes never disappear - history matters.
 */
export enum WorkNodeState {
  Planned = "planned",
  Ready = "ready",
  Running = "running",
  Waiting = "waiting",
  Blocked = "blocked",
  Review = "review",
  Completed = "completed",
  Cancelled = "cancelled",
  Failed = "failed",
  Archived = "archived",
}

// ============================================================================
// Work Node
// ============================================================================

/**
 * A node in the Work Graph representing one atomic unit of engineering work.
 */
export interface WorkNode {
  /** Unique node identifier */
  id: string;

  /** Display title */
  title: string;

  /** Detailed description of the work */
  description: string;

  /** Category of engineering work */
  type: WorkNodeType;

  /** Priority level (1-10, 10 = highest) */
  priority: number;

  /** Current state in the lifecycle */
  state: WorkNodeState;

  /** Estimated cost budget (in normalized compute units) */
  estimatedCost: number;

  /** Estimated token budget */
  estimatedTokens: number;

  /** Estimated time budget in milliseconds */
  estimatedTimeMs: number;

  /** Required capabilities to execute this node */
  requiredCapabilities: string[];

  /** Node IDs that must complete before this node can start */
  dependencies: string[];

  /** Risk level (0-1, 1 = highest risk) */
  risk: number;

  /** Complexity score (1-100) */
  complexity: number;

  /** Confidence in estimates (0-1, 1 = most confident) */
  confidence: number;

  /** Expected deliverables */
  expectedDeliverables: string[];

  /** Acceptance criteria for completion */
  acceptanceCriteria: string[];

  /** Assigned worker ID (set during scheduling) */
  assignedWorkerId?: string;

  /** Assigned provider name (set during scheduling) */
  assignedProvider?: string;

  /** Execution history entries */
  executionHistory: NodeExecutionRecord[];

  /** Knowledge artifacts generated by completing this node */
  knowledgeGenerated: string[];

  /** Timestamps for state transitions */
  createdAt: string;
  updatedAt: string;
  startedAt?: string;
  completedAt?: string;

  /** Metadata for arbitrary extension */
  metadata: Record<string, unknown>;
}

/**
 * Records one execution attempt of a node.
 */
export interface NodeExecutionRecord {
  /** Attempt number (1-based) */
  attempt: number;

  workerId: string;
  providerName: string;
  startedAt: string;
  finishedAt: string;
  durationMs: number;
  tokensUsed?: number;
  costIncurred: number;
  success: boolean;
  errorMessage?: string;
}

// ============================================================================
// Work Graph
// ============================================================================

/**
 * The complete work graph - an executable representation of engineering.
 */
export interface WorkGraph {
  /** Unique graph identifier */
  id: string;

  /** Version number (incremented each planning cycle) */
  version: number;

  /** Human-readable name */
  name: string;

  /** Associated mission ID */
  missionId: string;

  /** All nodes in the graph */
  nodes: Map<string, WorkNode>;

  /** Adjacency list: nodeId -> set of dependent node IDs */
  dependents: Map<string, Set<string>>;

  /** Metadata for arbitrary extension */
  metadata: Record<string, unknown>;

  /** Lifecycle state of the entire graph */
  state: WorkGraphLifecycleState;

  createdAt: string;
  updatedAt: string;
}

/**
 * Top-level lifecycle state of a work graph.
 */
export enum WorkGraphLifecycleState {
  Creating = "creating",
  Active = "active",
  Paused = "paused",
  Complete = "complete",
  Abandoned = "abandoned",
}

