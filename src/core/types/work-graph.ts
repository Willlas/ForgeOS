/**
 * Creates a new WorkNode with default values.
 */
export function createWorkNode(
  title: string,
  description: string,
  type: WorkNodeType,
  options?: {
    id?: string;
    priority?: number;
    dependencies?: string[];
    requiredCapabilities?: string[];
    estimatedCost?: number;
    estimatedTokens?: number;
    estimatedTimeMs?: number;
    metadata?: Record<string, unknown>;
  }
): WorkNode {
  const {
    id: customId,
    priority = 5,
    dependencies = [],
    requiredCapabilities = [],
    estimatedCost = 100,
    estimatedTokens = 10_000,
    estimatedTimeMs = 3_600_000, // 1 hour
    metadata = {},
  } = options ?? {};

  const now = new Date().toISOString();

  return {
    id: customId ?? generateNodeId(),
    title,
    description,
    type,
    priority: Math.max(1, Math.min(10, priority)),
    state: WorkNodeState.Planned,
    estimatedCost,
    estimatedTokens,
    estimatedTimeMs,
    requiredCapabilities,
    dependencies,
    risk: 0.5,
    complexity: 50,
    confidence: 0.7,
    expectedDeliverables: [],
    acceptanceCriteria: [],
    executionHistory: [],
    knowledgeGenerated: [],
    createdAt: now,
    updatedAt: now,
    metadata,
  };
}

/**
 * Creates a new WorkGraph with default values.
 */
export function createWorkGraph(
  name: string,
  missionId: string
): WorkGraph {
  const now = new Date().toISOString();
  return {
    id: generateNodeId({ prefix: "wg" }),
    version: 1,
    name,
    missionId,
    nodes: new Map(),
    dependents: new Map(),
    metadata: {},
    state: WorkGraphLifecycleState.Creating,
    createdAt: now,
    updatedAt: now,
  };
}